"""
E-Commerce Pricing Optimization Environment
==========================================
Custom RL environment for optimizing e-commerce pricing and discounts.
Simulates customer behavior based on historical RFM metrics, segment
loyalty, return risk, and payment methods.
"""

import numpy as np


class EcommerceEnvironment:
    """
    Simulates the Indian e-commerce environment for the RL agent.

    State space: Extracted features from the preprocessed data (demographics,
                 RFM scores, current order value, category, return rate).
    Action space: Discrete discount tiers (e.g., 0%, 5%, 10%, 15%, 20%, 25%, 30%).
    Reward: Profit generated by the order, adjusted for:
            - Customer Lifetime Value (CLV) retention boost
            - Return risk penalty (high discounts to return-prone segments)
            - Payment method adjustments (COD cancellation risk)
    """

    def __init__(self, data_dict: dict, max_steps: int = None):
        """
        Initialize the environment.

        Args:
            data_dict: Dictionary returned by EcommerceDataPreprocessor.process()
            max_steps: Maximum steps per episode (defaults to dataset length)
        """
        self.states = data_dict['states']
        self.actions = data_dict['actions']
        self.rewards = data_dict['rewards']
        self.dataframe = data_dict['dataframe']
        self.discount_bins = [0.0, 0.05, 0.10, 0.15, 0.20, 0.25, 0.30]

        # Action and State dims
        self.n_actions = len(self.discount_bins)
        self.state_dim = self.states.shape[1]

        self.max_steps = max_steps if max_steps is not None else len(self.states)
        self.current_step = 0
        
        # We pre-calculate some baseline values for counterfactual rewards
        self._cache_features()

    def _cache_features(self):
        """Extract needed columns for reward calculation to avoid DataFrame lookups per step."""
        if 'TotalAmount' in self.dataframe.columns:
            self.base_amounts = self.dataframe['TotalAmount'].values
        else:
            self.base_amounts = np.zeros(len(self.dataframe))
            
        if 'CustomerLTV' in self.dataframe.columns:
            self.ltvs = self.dataframe['CustomerLTV'].values
        else:
            self.ltvs = np.zeros(len(self.dataframe))
            
        if 'CustomerReturnRate' in self.dataframe.columns:
            self.return_rates = self.dataframe['CustomerReturnRate'].values
        else:
            self.return_rates = np.zeros(len(self.dataframe))
            
        if 'PaymentMethod' in self.dataframe.columns:
            self.is_cod = (self.dataframe['PaymentMethod'] == 'COD').values
        else:
            self.is_cod = np.zeros(len(self.dataframe), dtype=bool)
            
        # Base margins are assumed 8-25%
        self.base_margins = np.random.uniform(0.08, 0.25, size=len(self.dataframe))

    def reset(self) -> np.ndarray:
        """Reset the environment to the beginning of the dataset."""
        self.current_step = 0
        return self.states[self.current_step]

    def step(self, action: int) -> tuple[np.ndarray, float, bool, dict]:
        """
        Take an action and observe the next state and reward.

        Args:
            action: Index of the chosen discount bin.

        Returns:
            next_state: The state for the next step.
            reward: The calculated counterfactual reward.
            done: Whether the episode has ended.
            info: Additional debug information.
        """
        # Calculate counterfactual reward
        reward = self._calculate_reward(action, self.current_step)

        # Advance step
        self.current_step += 1
        done = self.current_step >= self.max_steps

        next_state = self.states[self.current_step] if not done else np.zeros(self.state_dim)
        
        info = {
            'step': self.current_step - 1,
            'action_taken': action,
            'discount': self.discount_bins[action]
        }

        return next_state, reward, done, info

    def _calculate_reward(self, action: int, step_idx: int) -> float:
        """
        Calculate the reward for applying a specific discount to the current order.
        
        Reward components:
        1. Base Profit = TotalAmount * (BaseMargin - Discount)
        2. Volume Boost = If discount is high, assume higher conversion (elasticity)
        3. LTV Boost = Small retention bonus for giving discounts to high-LTV customers
        4. Return Risk = Penalty if giving high discount to high-return-rate customer
        5. COD Risk = Slight penalty on COD orders as they might cancel/return more
        """
        discount = self.discount_bins[action]
        base_amount = self.base_amounts[step_idx]
        base_margin = self.base_margins[step_idx]
        ltv = self.ltvs[step_idx]
        return_rate = self.return_rates[step_idx]
        is_cod = self.is_cod[step_idx]
        
        # 1. Base Profit calculation
        # If discount > margin, profit becomes negative
        profit_margin = base_margin - discount
        
        # 2. Demand Elasticity (Volume Boost)
        # Higher discount -> higher chance of purchase. We model this as a multiplier on expected volume.
        # e.g., 0% discount = 1.0x volume, 30% discount = 1.5x volume
        elasticity_multiplier = 1.0 + (discount * 1.5)
        
        expected_profit = base_amount * profit_margin * elasticity_multiplier
        
        # Massive penalty if the transaction becomes unprofitable
        margin_penalty = 0.0
        if profit_margin < 0:
            margin_penalty = abs(expected_profit) * 5.0 # 5x penalty for losing money!
            
        # 3. LTV Retention Boost
        # We add a small fraction of their LTV as a future expected reward.
        ltv_boost = 0.0
        if discount > 0 and profit_margin > 0:
            ltv_boost = (ltv * 0.001 * discount)
            ltv_boost = min(ltv_boost, expected_profit * 0.2) # Cap at 20% of expected profit
            
        # 4. Return Risk Penalty
        # High discounts to people who return often is bad (they just buy because it's cheap and return anyway).
        return_penalty = 0.0
        if return_rate > 0.15: # If they return more than 15% of the time
            return_penalty = base_amount * return_rate * discount * 0.5
            
        # 5. COD Cancellation Risk
        # COD orders have higher RTO (Return to Origin).
        cod_penalty = 0.0
        if is_cod:
            cod_penalty = expected_profit * 0.1 # 10% haircut on expected profit for COD
            
        # Total Reward
        total_reward = expected_profit + ltv_boost - return_penalty - cod_penalty - margin_penalty
        
        # Normalize reward to help stable training
        # We divide by 100 to keep rewards generally in the [-10, 10] range
        normalized_reward = total_reward / 100.0
        
        return float(normalized_reward)
